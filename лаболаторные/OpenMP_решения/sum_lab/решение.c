/* ============================================================================
   ЛАБОРАТОРНАЯ: суммирование элементов массива в OpenMP.
   В одном файле: примеры 4a и 18a + основное задание (4 способа суммы).
   Массив заполнен единицами, значит правильная сумма = размеру массива N.
   Построчные пояснения даны в комментариях рядом с каждой строкой.
   ============================================================================ */

#include <stdio.h>   /* printf — вывод на экран                              */
#include <omp.h>     /* функции и директивы OpenMP (omp_get_thread_num и др.) */

/* ------------------------------------------------------------------ */
/* ПРИМЕР 4a. Опция reduction.                                        */
/* ------------------------------------------------------------------ */
void primer_4a(void)
{
    int count = 0;                              /* общий счётчик, старт = 0      */

#pragma omp parallel reduction(+: count)        /* создаём нити; у КАЖДОЙ своя   */
    {                                           /* копия count = 0, в конце все  */
                                                /* копии складываются (оператор +)*/
        count++;                                /* каждая нить увеличила свою копию на 1 */
        printf("Текущее значение count: %d\n", count); /* печать копии нити (обычно 1) */
    }                                           /* конец области: count = сумма копий = число нитей */

    printf("Число нитей: %d\n\n", count);       /* итог: сколько нитей работало  */
}

/* ------------------------------------------------------------------ */
/* ПРИМЕР 18a. Директива for — распределение итераций между нитями.   */
/* ------------------------------------------------------------------ */
void primer_18a(void)
{
    int A[10], B[10], C[10], i, n;              /* три массива, счётчик i, номер нити n */

    for (i = 0; i < 10; i++) {                  /* заполняем исходные массивы    */
        A[i] = i;                               /* A = 0,1,2,...,9               */
        B[i] = 2 * i;                           /* B = 0,2,4,...,18              */
        C[i] = 0;                               /* C обнуляем                    */
    }

#pragma omp parallel shared(A, B, C) private(i, n) /* A,B,C общие; i и n — у каждой нити свои */
    {
        n = omp_get_thread_num();               /* узнаём номер текущей нити (0,1,2,...) */

#pragma omp for                                 /* делим итерации цикла между нитями */
        for (i = 0; i < 10; i++)
        {
            C[i] = A[i] + B[i];                 /* каждая нить считает свою часть C */
            printf("Нить %d сложила элементы с номером %d\n", n, i);
        }
    }
    printf("\n");
}

/* ================================================================== */
/* ОСНОВНОЕ ЗАДАНИЕ: сумма элементов массива четырьмя способами.      */
/* ================================================================== */
int main(int argc, char *argv[])
{
    primer_4a();                                /* запускаем пример 4a           */
    primer_18a();                               /* запускаем пример 18a          */

    const int n = 1000000;                      /* размер массива (можно любой)  */
    static int a[1000000];                      /* сам массив (static — не в стеке) */
    int i;                                      /* счётчик цикла                 */
    long long sum;                              /* сумма (long long на всякий случай) */

    for (i = 0; i < n; i++)                     /* заполняем массив единицами,   */
        a[i] = 1;                               /* чтобы правильная сумма была = n */

    printf("Размер массива: %d\n", n);
    printf("Правильная сумма: %d\n\n", n);

    /* ---------- 1. omp for БЕЗ reduction (ГОНКА ДАННЫХ) ---------- */
    sum = 0;                                    /* ОБЯЗАТЕЛЬНО обнуляем sum перед областью */
#pragma omp parallel shared(a, sum)             /* sum общая для всех нитей       */
    {
#pragma omp for                                 /* итерации делятся между нитями  */
        for (i = 0; i < n; i++)
            sum += a[i];                         /* НЕ атомарно: читать->прибавить->записать */
    }                                            /* нити мешают друг другу, часть прибавлений теряется */
    printf("1) Без защиты (гонка):    sum = %lld\n", sum);
    /* ПОЯСНЕНИЕ: sum общая, а "sum += a[i]" состоит из 3 шагов. Две нити могут   */
    /* прочитать одно и то же старое значение, и одна запись затрёт другую.       */
    /* Поэтому результат МЕНЬШЕ n и РАЗНЫЙ при каждом запуске.                     */

    /* ---------- 2. omp for С reduction(+: sum) ---------- */
    sum = 0;                                    /* снова обнуляем sum            */
#pragma omp parallel shared(a) reduction(+: sum) /* у каждой нити своя копия sum, */
    {                                           /* в конце все копии складываются */
#pragma omp for
        for (i = 0; i < n; i++)
            sum += a[i];                         /* каждая нить копит в своей копии */
    }
    printf("2) reduction(+: sum):     sum = %lld\n", sum); /* всегда верно = n    */

    /* ---------- 3. omp for + atomic (пример 27a) ---------- */
    sum = 0;                                    /* обнуляем sum                  */
#pragma omp parallel shared(a, sum)
    {
        long long local_sum = 0;                /* частичная сумма — своя у каждой нити */
#pragma omp for
        for (i = 0; i < n; i++)
            local_sum += a[i];                   /* копим локально (гонки нет)     */
#pragma omp atomic                              /* прибавление к общей sum —      */
        sum += local_sum;                        /* атомарное (неделимое) действие */
    }
    printf("3) atomic:                sum = %lld\n", sum);

    /* ---------- 4. omp for + critical (пример 26a) ---------- */
    sum = 0;                                    /* обнуляем sum                  */
#pragma omp parallel shared(a, sum)
    {
        long long local_sum = 0;                /* частичная сумма нити          */
#pragma omp for
        for (i = 0; i < n; i++)
            local_sum += a[i];                   /* копим локально                 */
#pragma omp critical                            /* критическая секция: внутрь     */
        {                                       /* входит только одна нить за раз */
            sum += local_sum;                    /* безопасно прибавляем к общей sum */
        }
    }
    printf("4) critical:              sum = %lld\n", sum);

    return 0;
}

