#!/usr/bin/env bash
# =============================================================
#  Скрипт автоматизации для Linux / macOS
#  Что делает:
#    1. Обновляет исходники из git-репозитория (git pull)
#    2. Конфигурирует проект через CMake (режим Debug -> есть
#       отладочная информация для gdb)
#    3. Компилирует проект
#
#  Использование:
#    ./build.sh            # собрать lab_1 (по умолчанию)
#    ./build.sh lab_0      # собрать другую лабу
# =============================================================

# Прерывать выполнение при любой ошибке
set -e

# Папка проекта: первый аргумент или lab_1 по умолчанию
PROJECT_DIR="${1:-lab_1}"

# Переходим в директорию, где лежит сам скрипт (корень репозитория)
cd "$(dirname "$0")"

echo "=== [1/3] Обновление исходников из Git ==="
git pull

echo ""
echo "=== [2/3] Конфигурация CMake (${PROJECT_DIR}) ==="
# -S  — где лежат исходники (CMakeLists.txt)
# -B  — куда складывать файлы сборки
# CMAKE_BUILD_TYPE=Debug — добавляет флаг -g (символы для gdb)
cmake -S "${PROJECT_DIR}" -B "${PROJECT_DIR}/build" -DCMAKE_BUILD_TYPE=Debug

echo ""
echo "=== [3/3] Компиляция ==="
cmake --build "${PROJECT_DIR}/build"

echo ""
echo "=== Готово! Исполняемые файлы в ${PROJECT_DIR}/build/ ==="
